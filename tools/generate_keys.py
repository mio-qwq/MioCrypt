"""Generate the organizer-only RSA key pair and CNG public-key blob for MioCrypt."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa


BCRYPT_RSAPUBLIC_MAGIC = 0x31415352  # 'RSA1' in little-endian form.


def bytes_as_c_initializer(data: bytes, columns: int = 12) -> str:
    lines: list[str] = []
    for offset in range(0, len(data), columns):
        row = ", ".join(f"0x{value:02X}" for value in data[offset : offset + columns])
        lines.append(f"    {row},")
    return "\n".join(lines)


def write_public_blob_header(blob: bytes, destination: Path) -> None:
    destination.write_text(
        """// Generated by tools/generate_keys.py. This is intentionally public.
#pragma once

#include <stddef.h>
#include <stdint.h>

static const uint8_t kRsaPublicKeyBlob[] = {
"""
        + bytes_as_c_initializer(blob)
        + "\n};\n\n"
        + "static const size_t kRsaPublicKeyBlobSize = sizeof(kRsaPublicKeyBlob);\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="replace an existing organizer private key")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parents[1]
    organizer_dir = project_root / "local" / "organizer"
    source_dir = project_root / "src"
    organizer_dir.mkdir(parents=True, exist_ok=True)
    source_dir.mkdir(exist_ok=True)

    private_path = organizer_dir / "miocrypt_private_key.pem"
    public_pem_path = organizer_dir / "miocrypt_public_key.pem"
    public_blob_path = source_dir / "rsa_public_blob.h"
    if private_path.exists() and not args.force:
        raise SystemExit(f"Refusing to replace existing private key: {private_path}\nUse --force only when rotating the challenge key.")

    private_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    public_key = private_key.public_key()
    public_numbers = public_key.public_numbers()

    modulus_size = (public_numbers.n.bit_length() + 7) // 8
    exponent_size = max(1, (public_numbers.e.bit_length() + 7) // 8)
    modulus = public_numbers.n.to_bytes(modulus_size, "big")
    exponent = public_numbers.e.to_bytes(exponent_size, "big")
    bcrypt_header = struct.pack(
        "<LLLLLL",
        BCRYPT_RSAPUBLIC_MAGIC,
        modulus_size * 8,
        len(exponent),
        len(modulus),
        0,
        0,
    )
    bcrypt_blob = bcrypt_header + exponent + modulus

    private_path.write_bytes(
        private_key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    public_pem_path.write_bytes(
        public_key.public_bytes(
            serialization.Encoding.PEM,
            serialization.PublicFormat.SubjectPublicKeyInfo,
        )
    )
    write_public_blob_header(bcrypt_blob, public_blob_path)
    (organizer_dir / "KEY_INFO.txt").write_text(
        "This directory is organizer-only. Do NOT distribute miocrypt_private_key.pem.\n"
        "The executable embeds only src/rsa_public_blob.h.\n"
        "Key type: RSA-2048. Encryption padding: RSA-OAEP with SHA-256.\n",
        encoding="utf-8",
    )
    print(f"Private key: {private_path}")
    print(f"Public CNG blob header: {public_blob_path}")


if __name__ == "__main__":
    main()
